// Writes redteam/redteam.quick.yaml: only the single-turn attacks (direct + encodings) from the
// full generated set. Iterative strategies (jailbreak:meta, jailbreak:composite, crescendo) make
// many attacker/judge calls per attack, so they run in the scheduled CI job instead.
// Usage: node scripts/redteam-subset.mjs [strategy,strategy,...]
import { readFileSync, writeFileSync } from 'node:fs';
import { dump, load } from 'js-yaml';

const keep = new Set((process.argv[2] ?? 'basic,base64,leetspeak,rot13').split(','));
const suite = load(readFileSync('redteam/redteam.yaml', 'utf8'));
const before = suite.tests.length;
suite.tests = suite.tests.filter((t) => keep.has(t.metadata?.strategyId ?? 'basic'));
writeFileSync('redteam/redteam.quick.yaml', `# Generated by scripts/redteam-subset.mjs. Do not edit.\n${dump(suite, { lineWidth: -1 })}`);
console.log(`redteam.quick.yaml: ${suite.tests.length} of ${before} attacks (${[...keep].join(', ')})`);
